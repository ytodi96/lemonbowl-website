export function courseItems(course: CourseId): MenuItem[] {
  const entry = COURSES.find((c) => c.id === course);
  if (!entry) return [];
  return MENU.filter((item) => entry.categories.includes(item.category));
}

/** Cuisine chips available inside a course, derived from its items. */
export function courseCuisines(course: CourseId): string[] {
  const seen: string[] = [];
  for (const item of courseItems(course)) {
    if (item.cuisine && !seen.includes(item.cuisine)) seen.push(item.cuisine);
  }
  return seen;
}

